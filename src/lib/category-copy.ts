export function getCategoryIntro(opts: {
  slug: string;
  name: string;
  parentSlug?: string | null;
  parentName?: string | null;
}): { lead: string; note: string } {
  const family = FAMILY_COPY[opts.slug] ?? (opts.parentSlug ? FAMILY_COPY[opts.parentSlug] : null);

  if (family) {
    const lead = opts.parentSlug
      ? `«${opts.name}» یکی از زیردسته‌های «${opts.parentName}» در فروشگاه شیک است. ${family.short}`
      : family.lead;
    return { lead, note: family.note };
  }

  const lead = opts.parentSlug
    ? `«${opts.name}» یکی از زیردسته‌های «${opts.parentName}» در فروشگاه شیک است و با ضمانت اصالت و قیمت رقابتی عرضه می‌شود.`
    : `«${opts.name}» در فروشگاه شیک با ضمانت اصالت، قیمت رقابتی و پشتیبانی فنی عرضه می‌شود.`;
  return { lead, note: "برای انتخاب دقیق‌تر و مشاورهٔ فنی تخصصی با کارشناسان ما تماس بگیرید." };
}
